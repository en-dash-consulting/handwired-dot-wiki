import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
test('layout: drag by keyboard, learn, 0 out of bounds; generic model overflows', async ({ page }) => {
  test.setTimeout(60_000)
  const errors: string[] = []; page.on('pageerror', e => errors.push(String(e)))
  await page.goto('/pages/layout.html')
  await expect(page.locator('#demo-status')).toContainText('✓')
  await page.getByRole('slider', { name: 'Hero story width' }).focus()
  for (let i = 0; i < 5; i++) await page.keyboard.press('ArrowRight')
  await expect(page.locator('#ly-drags')).toContainText('1 drag')
  await page.getByRole('button', { name: /Simulate a designer/ }).click()
  await page.getByRole('button', { name: 'Learn from the drags' }).click()
  await expect(page.locator('#ly-msg')).toContainText('learned', { timeout: 20_000 })
  await expect(page.locator('#ly-oob')).toHaveText('0')
  await page.getByRole('button', { name: 'Never: the clamp is still in the code' }).click()
  await page.getByRole('button', { name: 'Train the generic model' }).click()
  await expect(page.locator('#ly-mlp-msg')).toContainText('Trained', { timeout: 20_000 })
  console.log('RESULT', await page.locator('#ly-code').textContent(), await page.locator('#ly-msg').textContent(), await page.locator('#ly-err').textContent(), await page.locator('#ly-jsdiff').textContent(), await page.locator('#ly-mlp-msg').textContent())
  await page.fill('#ly-vp', '320'); await page.locator('#ly-show-mlp').check()
  await page.waitForTimeout(800)
  const r = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(r.violations.filter(v => v.impact === 'serious' || v.impact === 'critical').map(v => v.id + ' ' + v.nodes.map(n => n.target).join())).toEqual([])
  expect(errors).toEqual([])
  if (process.env.SHOTS) for (const w of [390, 1280]) { await page.setViewportSize({ width: w, height: 900 }); await page.locator('#ly-screen').scrollIntoViewIfNeeded(); await page.screenshot({ path: `screenshots-review/layout-foil-320-${w}.png` }) }
})
