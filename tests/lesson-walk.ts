import { expect, type Page } from '@playwright/test'
type L = { predictions: Record<string, string>, race: { same: number, checked: number, worst: number }, landedOld: number, learn: { steps: number, landed: number, done: boolean, exportSame: number, params: Record<string, number> }, vs: { done: boolean, hwSteps: number, mlpSteps: number, hwFit: number, mlpFit: number, hwBad: number, mlpBad: number, hwLand: number, mlpLand: number } }
const L = (page: Page) => page.evaluate(() => (window as unknown as { lesson: L }).lesson)
const shot = (page: Page, name: string) => process.env.SHOTS && name.includes('-') ? page.screenshot({ path: `screenshots-review/lesson-${name}.png`, fullPage: false }) : Promise.resolve()

export async function walk(page: Page, tag = '') {
  const step = (n: number) => page.locator(`[data-step="${n}"]`)
  await page.goto('/pages/js-vs-nn.html')
  await expect(step(1).locator('.trace')).toContainText('shelf 62 cm')
  await step(1).locator('input[type=range]').focus(); await page.keyboard.press('ArrowRight')
  await expect(step(1).locator('.trace')).toContainText('shelf 63 cm')
  await expect(step(1).locator('.sc-say')).toHaveText('landed!', { timeout: 5000 })
  await step(1).scrollIntoViewIfNeeded(); await shot(page, `1${tag}`)
  await page.locator('[data-next="2"]').click()
  await step(2).locator('.choice[data-v="exact"]').click()
  await expect(step(2).locator('[data-eq]')).toHaveText('=')
  await page.waitForTimeout(1200); await step(2).locator('.reveal').scrollIntoViewIfNeeded(); await shot(page, `2${tag}`)
  await page.locator('[data-next="3"]').click()
  await step(3).locator('.choice[data-v="0"]').click()
  await expect(step(3).locator('[data-race]')).toHaveText('3,201', { timeout: 20000 })
  let s = await L(page); expect(s.race.same).toBe(3201); expect(s.race.worst).toBe(0)
  await step(3).locator('.reveal').scrollIntoViewIfNeeded(); await shot(page, `3${tag}`)
  await page.locator('[data-next="4"]').click()
  await step(4).locator('[data-feed]').click()
  await expect(page.locator('[data-next="5"]')).toBeVisible({ timeout: 30000 })
  s = await L(page); expect(s.landedOld).toBe(0)
  await step(4).locator('.reveal').scrollIntoViewIfNeeded(); await shot(page, `4${tag}`)
  await page.locator('[data-next="5"]').click()
  await step(5).locator('[data-learn]').click()
  await expect(page.locator('[data-next="6"]')).toBeVisible({ timeout: 60000 })
  s = await L(page); expect(s.learn.landed).toBe(12); expect(s.learn.exportSame).toBe(3201)
  await step(5).locator('.reveal').scrollIntoViewIfNeeded(); await shot(page, `5${tag}`)
  await page.locator('[data-next="6"]').click()
  await step(6).locator('[data-race6]').click()
  await expect(page.locator('[data-next="7"]')).toBeVisible({ timeout: 90000 })
  s = await L(page); expect(s.vs.hwBad).toBe(0); expect(s.vs.hwLand).toBeGreaterThan(s.vs.mlpLand)
  await step(6).locator('.reveal').scrollIntoViewIfNeeded(); await shot(page, `6${tag}`)
  await page.locator('[data-next="7"]').click()
  await expect(step(7)).toBeVisible(); await shot(page, `7${tag}`)
  return s
}
